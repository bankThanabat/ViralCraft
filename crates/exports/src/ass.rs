//! Advanced SubStation Alpha captions: styles from the caption styles,
//! one Dialogue line per caption, positioned with `\an` and `\pos`.

use std::fmt::Write;

use model::inspect::caption_styles;
use model::{Animation, BoxN, Inspect, Probe, RationalTime};

pub fn ass_time(seconds: f64) -> String {
    let cs = (seconds * 100.0).round().max(0.0) as u64;
    format!(
        "{}:{:02}:{:02}.{:02}",
        cs / 360_000,
        cs / 6000 % 60,
        cs / 100 % 60,
        cs % 100
    )
}

/// `#RRGGBB` to ASS `&HAABBGGRR` with full opacity.
pub fn ass_colour(hex: &str) -> String {
    let h = hex.trim_start_matches('#');
    if h.len() != 6 {
        return "&H00000000".to_string();
    }
    format!("&H00{}{}{}", &h[4..6], &h[2..4], &h[0..2]).to_uppercase()
}

/// The point `\pos` refers to for an `an1`..`an9` anchor, in pixels.
pub fn anchor_point(anchor: &str, b: &BoxN, width: u32, height: u32) -> (i64, i64) {
    let n: u32 = anchor.trim_start_matches("an").parse().unwrap_or(5);
    let x = match n % 3 {
        1 => b.left(),
        2 => b.cx,
        _ => b.right(),
    };
    let y = match n {
        7..=9 => b.top(),
        4..=6 => b.cy,
        _ => b.bottom(),
    };
    (
        (x * f64::from(width)).round() as i64,
        (y * f64::from(height)).round() as i64,
    )
}

pub fn write(probe: &Probe, inspect: &Inspect) -> String {
    let caps = &inspect.captions;
    let mut out = String::new();
    let _ = writeln!(out, "[Script Info]");
    let _ = writeln!(out, "; Generated by ViralCraft from inspect.json.");
    let _ = writeln!(
        out,
        "; Fonts are unknown: replace Arial with the substitutes chosen in EDIT-SPEC.md."
    );
    let _ = writeln!(
        out,
        "; Outline width and box padding are estimated from font size, not measured."
    );
    let _ = writeln!(out, "ScriptType: v4.00+");
    let _ = writeln!(out, "PlayResX: {}", probe.width);
    let _ = writeln!(out, "PlayResY: {}", probe.height);
    let _ = writeln!(out, "ScaledBorderAndShadow: yes");
    let _ = writeln!(out, "WrapStyle: 2\n");

    let styles = caption_styles(caps);
    let _ = writeln!(out, "[V4+ Styles]");
    let _ = writeln!(
        out,
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding"
    );
    for (id, members) in &styles {
        let c = &caps[members[0]];
        let mut sizes: Vec<f64> = members.iter().map(|&i| caps[i].font_px_estimate).collect();
        sizes.sort_by(f64::total_cmp);
        let size = sizes[sizes.len() / 2].round().max(1.0);
        let fill = ass_colour(&c.fill);
        let (border_style, edge, back, width) = match (&c.box_color, &c.outline) {
            (Some(b), _) => (3, ass_colour(b), ass_colour(b), (size * 0.25).round()),
            (None, Some(o)) => (
                1,
                ass_colour(o),
                "&H00000000".to_string(),
                (size * 0.04).round().max(1.0),
            ),
            (None, None) => (1, "&H00000000".to_string(), "&H00000000".to_string(), 0.0),
        };
        let align = c.anchor.trim_start_matches("an");
        let _ = writeln!(
            out,
            "Style: {id},Arial,{size},{fill},{fill},{edge},{back},-1,0,0,0,100,100,0,0,{border_style},{width},0,{align},0,0,0,1"
        );
    }

    let _ = writeln!(out, "\n[Events]");
    let _ = writeln!(
        out,
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
    );
    let secs = |f: i64| RationalTime::from_frames(f, probe.rate).to_seconds();
    let ms = |frames: u64| (frames as f64 * 1000.0 / probe.rate.as_f64()).round() as i64;
    for (i, c) in caps.iter().enumerate() {
        let style = styles
            .iter()
            .find(|(_, m)| m.contains(&i))
            .map_or("C1", |(id, _)| id.as_str());
        let (x, y) = anchor_point(&c.anchor, &c.bounds, probe.width, probe.height);
        let place = match c.animation {
            Some(Animation::Slide { frames, dx, dy }) => {
                let x0 = x + (dx * f64::from(probe.width)).round() as i64;
                let y0 = y + (dy * f64::from(probe.height)).round() as i64;
                format!(r"\move({x0},{y0},{x},{y},0,{})", ms(frames))
            }
            Some(Animation::PopIn { frames, from_scale }) => {
                let f = from_scale.round();
                format!(
                    r"\pos({x},{y})\fscx{f}\fscy{f}\t(0,{},\fscx100\fscy100)",
                    ms(frames)
                )
            }
            None => format!(r"\pos({x},{y})"),
        };
        let text = c
            .text
            .replace('\n', r"\N")
            .replace('{', "(")
            .replace('}', ")");
        let _ = writeln!(
            out,
            "Dialogue: 0,{},{},{style},,0,0,0,,{{\\{}{place}}}{text}",
            ass_time(secs(c.range.start.value)),
            ass_time(secs(c.range.end_frame())),
            c.anchor
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::testdata::cuts3;
    use model::BoxN;

    #[test]
    fn times_are_centiseconds() {
        assert_eq!(ass_time(1.8), "0:00:01.80");
        assert_eq!(ass_time(3725.256), "1:02:05.26");
    }

    #[test]
    fn colours_are_alpha_blue_green_red() {
        assert_eq!(ass_colour("#FFE600"), "&H0000E6FF");
        assert_eq!(ass_colour("#000000"), "&H00000000");
    }

    #[test]
    fn the_position_is_the_anchor_point_of_the_box() {
        let b = BoxN {
            cx: 0.5,
            cy: 0.2,
            w: 0.4,
            h: 0.1,
        };
        assert_eq!(anchor_point("an8", &b, 1080, 1920), (540, 288));
        assert_eq!(anchor_point("an5", &b, 1080, 1920), (540, 384));
        assert_eq!(anchor_point("an1", &b, 1080, 1920), (324, 480));
    }

    #[test]
    fn a_boxed_caption_uses_border_style_3() {
        let (probe, _, mut inspect) = cuts3();
        inspect.captions[0].box_color = Some("#000000".into());
        inspect.captions[0].outline = None;
        let out = write(&probe, &inspect);
        let style = out.lines().find(|l| l.starts_with("Style: C1")).unwrap();
        let fields: Vec<&str> = style.trim_start_matches("Style: ").split(',').collect();
        assert_eq!(fields[15], "3", "BorderStyle in {style}");
    }

    #[test]
    fn a_pop_in_animates_scale() {
        let (probe, _, mut inspect) = cuts3();
        inspect.captions[1].animation = Some(model::Animation::PopIn {
            frames: 4,
            from_scale: 80.0,
        });
        let out = write(&probe, &inspect);
        assert!(
            out.contains(r"\fscx80\fscy80\t(0,133,\fscx100\fscy100)"),
            "{out}"
        );
    }

    #[test]
    fn cuts_3_ass_snapshot() {
        let (probe, _, inspect) = cuts3();
        insta::assert_snapshot!(write(&probe, &inspect));
    }
}
